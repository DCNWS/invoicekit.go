package xsd

import (
	"fmt"
	"io"
	"sort"
	"strings"
)

// Prune returns a model holding only the components reachable from the given
// global element declarations, which is how the 2.9 MB of vendored XSD becomes
// a few hundred KB at runtime. Terms are shared, not copied.
func (m *Model) Prune(roots []string) (*Model, error) {
	out := NewModel()
	out.Source = m.Source
	out.Roots = append([]string(nil), roots...)
	seenT := map[*Type]bool{}
	var walkType func(t *Type)
	var walkDecl func(d *Decl)
	walkType = func(t *Type) {
		if t == nil || seenT[t] {
			return
		}
		seenT[t] = true
		if t.ID != "" {
			out.Types[t.ID] = t
		}
		walkTerms(t.Term, walkType, walkDecl)
	}
	walkDecl = func(d *Decl) {
		if d == nil {
			return
		}
		if _, done := out.Decls[d.ID]; !done {
			out.Decls[d.ID] = d
		}
		walkType(d.Type)
	}
	for _, id := range roots {
		d, ok := m.Decls[id]
		if !ok {
			return nil, fmt.Errorf("root element %s is not declared", show(id))
		}
		walkDecl(d)
	}
	// A content model that refers to a global element by ref needs that
	// declaration to exist on its own, so any ref whose declaration was not
	// reached from a root is a hole in the pruned model.
	for _, d := range m.Decls {
		if _, ok := out.Decls[d.ID]; !ok {
			for _, t := range out.Types {
				if refsDecl(t.Term, d.ID) {
					return nil, fmt.Errorf("pruned model refers to undeclared element %s", show(d.ID))
				}
			}
		}
	}
	return out, nil
}

// refsDecl reports whether any term under t points at a global element with
// the given id.
func refsDecl(t *Term, id string) bool {
	seen := map[*Term]bool{}
	var visit func(p *Term) bool
	visit = func(p *Term) bool {
		if p == nil || seen[p] {
			return false
		}
		seen[p] = true
		if p.DeclRef == id {
			return true
		}
		for _, q := range p.Parts {
			if visit(q) {
				return true
			}
		}
		if p.Type != nil {
			return visit(p.Type.Term)
		}
		return false
	}
	return visit(t)
}

// walkTerms visits every term under t, calling fnT on each content type and
// fnD on each global element declaration a ref points at.
func walkTerms(t *Term, fnT func(*Type), fnD func(*Decl)) {
	seen := map[*Term]bool{}
	var visit func(p *Term)
	visit = func(p *Term) {
		if p == nil || seen[p] {
			return
		}
		seen[p] = true
		if p.Type != nil {
			fnT(p.Type)
		}
		if p.Decl != nil {
			fnD(p.Decl)
		}
		for _, q := range p.Parts {
			visit(q)
		}
	}
	visit(t)
}

// Write emits the model in the same XSD dialect the reader understands, minus
// annotations, simple types and everything unreachable. The generated document
// is what the library parses at runtime.
func (m *Model) Write(w io.Writer) error {
	byNS := map[string]*nsGroup{}
	group := func(ns string) *nsGroup {
		g := byNS[ns]
		if g == nil {
			g = &nsGroup{ns: ns}
			byNS[ns] = g
		}
		return g
	}
	ids := make([]string, 0, len(m.Decls))
	for id := range m.Decls {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		d := m.Decls[id]
		g := group(d.NS)
		g.decls = append(g.decls, d)
	}
	ids = ids[:0]
	for id := range m.Types {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		t := m.Types[id]
		g := group(t.NS)
		g.types = append(g.types, t)
	}
	nss := make([]string, 0, len(byNS))
	for ns := range byNS {
		nss = append(nss, ns)
	}
	sort.Strings(nss)

	b := &strings.Builder{}
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	b.WriteString("<!--\n  Generated by cmd/xsdgen. Do not edit.\n")
	if src := sanitize(m.Source); src != "" {
		b.WriteString("  Derived from: " + src + "\n")
	}
	b.WriteString("-->\n")
	b.WriteString(`<xs:schemas xmlns:xs="` + xsNS + `">` + "\n")
	for _, ns := range nss {
		g := byNS[ns]
		fmt.Fprintf(b, "  <xs:schema elementFormDefault=\"qualified\"%s>\n", attr("targetNamespace", ns))
		for _, d := range g.decls {
			fmt.Fprintf(b, "    <xs:element name=%s%s/>\n", quote(local(d.ID)), typeAttr(d.Type))
		}
		for _, t := range g.types {
			if t.Term == nil {
				fmt.Fprintf(b, "    <xs:complexType name=%s/>\n", quote(local(t.ID)))
				continue
			}
			fmt.Fprintf(b, "    <xs:complexType name=%s>\n", quote(local(t.ID)))
			if err := writeTerm(b, t.Term, "      ", 0, ns); err != nil {
				return fmt.Errorf("complexType %s: %w", t.ID, err)
			}
			b.WriteString("    </xs:complexType>\n")
		}
		b.WriteString("  </xs:schema>\n")
	}
	b.WriteString("</xs:schemas>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// nsGroup collects the components of one target namespace for output.
type nsGroup struct {
	ns    string
	decls []*Decl
	types []*Type
}

// writeTerm emits one content term. tns is the target namespace of the schema
// being written, needed to keep local element declarations qualified.
func writeTerm(b *strings.Builder, t *Term, pad string, depth int, tns string) error {
	if depth > 24 {
		return fmt.Errorf("content model nested too deeply")
	}
	switch t.Kind {
	case Seq, Choice:
		name := "sequence"
		if t.Kind == Choice {
			name = "choice"
		}
		fmt.Fprintf(b, "%s<xs:%s%s>\n", pad, name, occAttr(t))
		for _, p := range t.Parts {
			if err := writeTerm(b, p, pad+"  ", depth+1, tns); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s</xs:%s>\n", pad, name)
	case Any:
		fmt.Fprintf(b, "%s<xs:any%s%s/>\n", pad, attr("namespace", t.AnyNS), occAttr(t))
	default:
		ref := ""
		form := ""
		if t.DeclRef != "" {
			ref = attr("ref", t.DeclRef)
		} else {
			ref = attr("name", local(t.Name))
			if ns, _ := splitClark(t.Name); ns != tns {
				form = ` form="unqualified"`
			}
		}
		ta := typeAttr(t.Type)
		if t.Type != nil && t.Type.ID == "" && t.Type.Term != nil {
			fmt.Fprintf(b, "%s<xs:element%s%s%s>\n", pad, ref, form, occAttr(t))
			if err := writeTerm(b, t.Type.Term, pad+"  ", depth+1, tns); err != nil {
				return err
			}
			b.WriteString(pad + "</xs:element>\n")
			return nil
		}
		fmt.Fprintf(b, "%s<xs:element%s%s%s%s/>\n", pad, ref, form, ta, occAttr(t))
	}
	return nil
}

// typeAttr refers to a named content type, or nothing for a leaf.
func typeAttr(t *Type) string {
	if t == nil || t.ID == "" || t.Term == nil {
		return ""
	}
	return attr("type", t.ID)
}

func occAttr(t *Term) string {
	s := ""
	if t.Min != 1 {
		s += fmt.Sprintf(" minOccurs=\"%d\"", t.Min)
	}
	switch {
	case t.Max < 0:
		s += " maxOccurs=\"unbounded\""
	case t.Max != 1:
		s += fmt.Sprintf(" maxOccurs=\"%d\"", t.Max)
	}
	return s
}

// quote renders a bare quoted value, used for local names.
func quote(v string) string { return attr("", v) }

// attr renders name="value", or just "value" when the name is empty.
func attr(name, v string) string {
	q := `"` + escape(v) + `"`
	if name == "" {
		return q
	}
	return " " + name + "=" + q
}

func escape(v string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;")
	return r.Replace(v)
}

// sanitize keeps a comment legal.
func sanitize(s string) string {
	s = strings.ReplaceAll(s, "--", "-")
	return strings.ReplaceAll(s, ">", "")
}
