// sRGBProfile returns a self-generated ICC profile for the sRGB colour space
// (IEC 61966-2-1), in the v4 profile format. PDF/A requires an OutputIntent
// with an ICC profile, and generating it here avoids shipping a third-party
// binary blob of uncertain licence.
//
// The matrix columns come straight from the sRGB specification: the xy
// chromaticities of the primaries and the D65 white point, converted to XYZ
// and then chromatically adapted to the D50 PCS illuminant with the Bradford
// transform. The tone reproduction curves are exact lookup tables of the
// sRGB companding function, which is more accurate than the parametric
// approximations and universally supported.
// iccVersion is the format version recorded in the header: ICC.1:2022, that is
// 4.3.0. PDF/A-2 and later require a v4 profile, and the desc tag written below
// uses the 4.3 structure with its empty Script code name.
const iccVersion = 0x04300000

func sRGBProfile() []byte {
	const (
		// IEC 61966-2-1 chromaticity coordinates.
		rx, ry = 0.6400, 0.3300
		gx, gy = 0.3000, 0.6000
		bx, by = 0.1500, 0.0600
		wx, wy = 0.3127, 0.3290 // D65
	)
	// Uncadapted RGB->XYZ columns (Y == 1 for each primary).
	cols := [3][3]float64{
		{rx / ry, 1, (1 - rx - ry) / ry},
		{gx / gy, 1, (1 - gx - gy) / gy},
		{bx / by, 1, (1 - bx - by) / by},
	}
	// Solve for the scaling that maps the white point to (Xw, 1, Zw).
	white := [3]float64{wx / wy, 1, (1 - wx - wy) / wy}
	z := solve3(cols, white)
	for c := range 3 {
		for r := range 3 {
			cols[c][r] *= z[c]
		}
	}
	// Bradford adaptation D65 -> D50.
	bradford := [3][3]float64{
		{0.8951, 0.2664, -0.1614},
		{-0.7502, 1.7135, 0.0367},
		{0.0389, -0.0685, 1.0296},
	}
	wd65 := [3]float64{wx / wy, 1, (1 - wx - wy) / wy}
	wd50 := [3]float64{0.9642, 1.0000, 0.8249} // D50 PCS illuminant
	adaptation := adapt(bradford, wd65, wd50)
	var adapted [3][3]float64
	for c := range 3 {
		for r := range 3 {
			adapted[c][r] = adaptation[r][0]*cols[c][0] + adaptation[r][1]*cols[c][1] + adaptation[r][2]*cols[c][2]
		}
	}

	const trcEntries = 1024
	trc := make([]byte, 8+2*trcEntries)
	copy(trc, "curv")
	binary.BigEndian.PutUint32(trc[4:], trcEntries)
	for i := range trcEntries {
		v := float64(i) / float64(trcEntries-1)
		l := sRGBLinearize(v)
		binary.BigEndian.PutUint16(trc[8+2*i:], uint16(math.Round(l*65535)))
	}

	desc := descriptionTag("sRGB IEC 61966-2-1 (generated by InvoiceKit)")
	cprt := textTag("Public domain. Generated from the IEC 61966-2-1 " +
		"transfer function and primaries; no third-party profile data.")

	tags := []struct {
		sig  string
		data []byte
	}{
		{"bXYZ", xyzTag(adapted[2])},
		{"bkpt", xyzTag([3]float64{0, 0, 0})},
		{"bTRC", trc},
		{"chad", s15Tag(adaptation)},
		{"cprt", cprt},
		{"desc", desc},
		{"gTRC", trc},
		{"gXYZ", xyzTag(adapted[1])},
		{"wtpt", xyzTag(wd50)},
		{"rXYZ", xyzTag(adapted[0])},
		{"rTRC", trc},
	}
	// Every tag's data has to start on a 4-byte boundary, and the length
	// recorded in the table includes that padding.
	for i := range tags {
		tags[i].data = pad4(tags[i].data)
	}
	// ICC requires the tag table to be sorted by signature.
	sortTags(tags)
	for i := 1; i < len(tags); i++ {
		if tags[i].sig == tags[i-1].sig {
			panic("pdf: duplicate ICC tag " + tags[i].sig)
		}
	}

	const headerSize = 128
	tableSize := 4 + 12*len(tags)
	size := headerSize + tableSize
	place := make(map[string]int)
	placed := make(map[int][]byte) // offset -> data, to share identical blocks
	for _, t := range tags {
		data := t.data
		if prev, ok := findPlaced(placed, data); ok {
			place[t.sig] = prev
			continue
		}
		place[t.sig] = size
		placed[size] = data
		size += len(data)
	}

	p := make([]byte, size)
	binary.BigEndian.PutUint32(p[0:], uint32(size))
	copy(p[4:], "\x00\x00\x00\x00") // preferred CMM: none
	binary.BigEndian.PutUint32(p[8:], iccVersion)
	copy(p[12:], "mntr")
	copy(p[16:], "RGB ")
	copy(p[20:], "XYZ ")
	// Creation date: fixed so the profile is byte-for-byte reproducible.
	p[24], p[25], p[26], p[27] = 0x07, 0xE9, 0x01, 0x01 // 2025-01-01 00:00
	p[28], p[29], p[30] = 0x00, 0x00, 0x00
	copy(p[36:], "acsp")
	binary.BigEndian.PutUint32(p[64:], 0) // rendering intent: perceptual
	// PCS illuminant: the D50 connection space in s15Fixed16. The header
	// states which illuminant the XYZ tags are referred to, so it has to agree
	// with wtpt and with the adaptation matrix below.
	for i, f := range wd50 {
		binary.BigEndian.PutUint32(p[68+4*i:], uint32(int64(math.Round(f*65536))))
	}
	copy(p[80:], "Kit ") // creator
	// Profile ID left zero, as permitted by the specification.

	binary.BigEndian.PutUint32(p[128:], uint32(len(tags)))
	off := 132
	for _, t := range tags {
		copy(p[off:], t.sig)
		binary.BigEndian.PutUint32(p[off+4:], uint32(place[t.sig]))
		binary.BigEndian.PutUint32(p[off+8:], uint32(len(t.data)))
		off += 12
	}
	for offset, data := range placed {
		copy(p[offset:], data)
	}
	return p
}

// pad4 appends the NUL padding that lets ICC tag data start on a 4-byte
// boundary; the tag's recorded length includes the padding.
func pad4(data []byte) []byte {
	if pad := len(data) % 4; pad != 0 {
		return append(slices.Clip(data), make([]byte, 4-pad)...)
	}
	return data
}

func findPlaced(placed map[int][]byte, data []byte) (int, bool) {
	for off, d := range placed {
		if bytes.Equal(d, data) {
			return off, true
		}
	}
	return 0, false
}

func sortTags(tags []struct {
	sig  string
	data []byte
}) {
	for i := 1; i < len(tags); i++ {
		for j := i; j > 0 && tags[j-1].sig > tags[j].sig; j-- {
			tags[j-1], tags[j] = tags[j], tags[j-1]
		}
	}
}

// sRGBLinearize applies the inverse of the sRGB companding function.
func sRGBLinearize(v float64) float64 {
	if v <= 0.04045 {
		return v / 12.92
	}
	return math.Pow((v+0.055)/1.055, 2.4)
}

func xyzTag(v [3]float64) []byte {
	b := make([]byte, 20)
	copy(b, "XYZ ")
	binary.BigEndian.PutUint32(b[4:], 0)
	for i, f := range v {
		binary.BigEndian.PutUint32(b[8+4*i:], uint32(int64(math.Round(f*65536))))
	}
	return b
}

// s15Tag builds an sf32Type structure holding a 3x3 matrix in s15Fixed16,
// the form ICC uses for the chad (chromatic adaptation) tag.
func s15Tag(m [3][3]float64) []byte {
	b := make([]byte, 8+9*4)
	copy(b, "sf32")
	i := 0
	for r := range 3 {
		for c := range 3 {
			binary.BigEndian.PutUint32(b[8+4*i:], uint32(int64(math.Round(m[r][c]*65536))))
			i++
		}
	}
	return b
}

// descriptionTag builds a "desc" tag as specified by ICC.1:2022 clause 8.4.2:
// an ASCII count, a reserved field, a Unicode count, two more reserved fields,
// the NUL-terminated ASCII text and a Script code name. The Unicode text and
// the Script code name are both empty, which the specification allows.
func descriptionTag(text string) []byte {
	// sig(4) + ASCII count(4) + reserved(4) + Unicode count(4) +
	// reserved(4) + reserved(4) + ASCII text and NUL + script code(6)
	buf := make([]byte, 24+len(text)+1+6)
	copy(buf, "desc")
	binary.BigEndian.PutUint32(buf[4:], uint32(len(text)+1)) // includes the NUL
	copy(buf[24:], text)
	buf[24+len(text)] = 0
	return buf
}

// textTag builds a textType structure: a signature, a reserved field and a
// NUL-terminated ASCII string. The string is not length-prefixed.
func textTag(s string) []byte {
	b := make([]byte, 8+len(s)+1)
	copy(b, "text")
	copy(b[8:], s)
	return b
}

// solve3 solves m * x = v for a 3x3 matrix given column-wise.
func solve3(m [3][3]float64, v [3]float64) [3]float64 {
	// Columns of m are m[c][r]; build row-major for Gaussian elimination.
	a := [3][4]float64{
		{m[0][0], m[1][0], m[2][0], v[0]},
		{m[0][1], m[1][1], m[2][1], v[1]},
		{m[0][2], m[1][2], m[2][2], v[2]},
	}
	for col := range 3 {
		piv := pivotRow(a, col)
		a[col], a[piv] = a[piv], a[col]
		d := a[col][col]
		if math.Abs(d) < 1e-12 {
			panic("pdf: singular matrix in ICC generation")
		}
		for r := range 3 {
			if r == col {
				continue
			}
			f := a[r][col] / d
			for c := col; c < 4; c++ {
				a[r][c] -= f * a[col][c]
			}
		}
	}
	return [3]float64{a[0][3] / a[0][0], a[1][3] / a[1][1], a[2][3] / a[2][2]}
}

// pivotRow returns the row at or below col whose entry in column col has the
// largest magnitude, for partial pivoting.
func pivotRow(a [3][4]float64, col int) int {
	piv := col
	for r := col + 1; r < 3; r++ {
		if math.Abs(a[r][col]) > math.Abs(a[piv][col]) {
			piv = r
		}
	}
	return piv
}

// adapt returns the chromatic adaptation matrix that takes white from to in
// the given cone domain. The scaling happens between the transform into the
// cone domain and the transform back, so the order is b⁻¹ · diag · b and not
// the other way round: scaling XYZ directly is a different, wrong matrix.
func adapt(b [3][3]float64, from, to [3]float64) [3][3]float64 {
	f := matMulVec(b, from)
	t := matMulVec(b, to)
	d := [3][3]float64{
		{t[0] / f[0], 0, 0},
		{0, t[1] / f[1], 0},
		{0, 0, t[2] / f[2]},
	}
	return matMul(matInv(b), matMul(d, b))
}

func matMul(a, b2 [3][3]float64) [3][3]float64 {
	var c [3][3]float64
	for r := range 3 {
		for k := range 3 {
			c[r][k] = a[r][0]*b2[0][k] + a[r][1]*b2[1][k] + a[r][2]*b2[2][k]
		}
	}
	return c
}

func matMulVec(a [3][3]float64, v [3]float64) [3]float64 {
	return [3]float64{
		a[0][0]*v[0] + a[0][1]*v[1] + a[0][2]*v[2],
		a[1][0]*v[0] + a[1][1]*v[1] + a[1][2]*v[2],
		a[2][0]*v[0] + a[2][1]*v[1] + a[2][2]*v[2],
	}
}

func matInv(a [3][3]float64) [3][3]float64 {
	det := a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1]) -
		a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0]) +
		a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0])
	if math.Abs(det) < 1e-12 {
		panic("pdf: singular matrix in ICC adaptation")
	}
	inv := 1 / det
	return [3][3]float64{
		{(a[1][1]*a[2][2] - a[1][2]*a[2][1]) * inv,
			(a[0][2]*a[2][1] - a[0][1]*a[2][2]) * inv,
			(a[0][1]*a[1][2] - a[0][2]*a[1][1]) * inv},
		{(a[1][2]*a[2][0] - a[1][0]*a[2][2]) * inv,
			(a[0][0]*a[2][2] - a[0][2]*a[2][0]) * inv,
			(a[0][2]*a[1][0] - a[0][0]*a[1][2]) * inv},
		{(a[1][0]*a[2][1] - a[1][1]*a[2][0]) * inv,
			(a[0][1]*a[2][0] - a[0][0]*a[2][1]) * inv,
			(a[0][0]*a[1][1] - a[0][1]*a[1][0]) * inv},
	}
}

// SRGBProfileHash is the SHA-256-free identity of the generated profile, used
// in tests to detect accidental changes.
func SRGBProfileMD5() string {
	sum := md5.Sum(sRGBProfile())
	return string(hexEncode(sum[:]))
}

func hexEncode(b []byte) []byte {
	const digits = "0123456789abcdef"
	out := make([]byte, 0, 2*len(b))
	for _, c := range b {
		out = append(out, digits[c>>4], digits[c&0xf])
	}
	return out
}

// SRGBProfile returns the generated sRGB ICC profile. A PDF/A OutputIntent
// needs one, and this keeps the file self-contained: no third-party profile
// binary has to be shipped or downloaded.
func SRGBProfile() []byte { return sRGBProfile() }
